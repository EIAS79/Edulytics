'use strict';
const fs=require('node:fs');
const path=require('node:path');
const base=path.resolve(__dirname,'../../artifacts/curriculum-delivery/US-CCSS-MATH/G12');
const progress=JSON.parse(fs.readFileSync(path.join(base,'full-grade-progress.json'),'utf8'));
const ledger=JSON.parse(fs.readFileSync(path.join(base,'grade12-stage-d-execution-ledger.json'),'utf8'));
const errors=[];
const first=progress.LessonEntries[0];
const handoff=fs.readFileSync(path.join(base,'grade12-a-c-handoff.md'),'utf8');
if (handoff.includes('Status: INCOMPLETE')||handoff.includes('not a Stage D handoff')) errors.push('A_C_HANDOFF_DOCUMENT_NOT_RECONCILED');
if (first.SemanticEquivalenceVerified!==true || first.SourceElementsIndependentlyMatched===0) errors.push('L01_SEMANTIC_PARITY_NOT_VERIFIED');
if (first.RightsVerified!==true)errors.push('L01_RIGHTS_NOT_VERIFIED');
if (!first.ExerciseRoutingRuntimeBound)errors.push('L01_ASSESSMENT_RUNTIME_NOT_BOUND');
if (ledger.sourceParity.denominator==null||ledger.sourceParity.numerator==null)errors.push('GRADE_SOURCE_PARITY_DENOMINATOR_OR_NUMERATOR_UNKNOWN');
if (ledger.digitalCoverage.denominator==null||ledger.digitalCoverage.numerator==null)errors.push('GRADE_DIGITAL_COVERAGE_DENOMINATOR_OR_NUMERATOR_UNKNOWN');
if (ledger.lessonResults.some(x=>x.dStatus==='D_BLOCKED'))errors.push('UNRESOLVED_STAGE_D_BLOCKED_LESSONS');
if (ledger.dVerifiedCount!==73)errors.push('GRADE12_NOT_ALL_D_VERIFIED');
if (ledger.academicApprovedCount!==73)errors.push('GRADE12_HUMAN_ACADEMIC_APPROVAL_INCOMPLETE');
console.log(JSON.stringify({gate:'Grade12 Stage D fail-closed acceptance',candidate:ledger.baselineCandidateSha,errors},null,2));
if(errors.length)process.exitCode=1;

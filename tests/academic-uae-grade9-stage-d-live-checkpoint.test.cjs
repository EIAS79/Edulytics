 const selection=read(b+'source-selection.json');
 const raw=read(b+'semantic-audit-ledger.json');
 const canonical=read(b+'grade9-82-target-index.json');
 const run=read(b+'grade9-stage-d-execution-ledger.json');
 assert.ok(handoff.includes('GRADE9_STAGE_D_HANDOFF_GATE=D_PENDING_A_C_EVIDENCE'));
 assert.equal(gate.decision,'NO_GO_SOURCE_100');
 assert.equal(gate.stageDEntryGate,'D_PENDING_A_C_EVIDENCE');

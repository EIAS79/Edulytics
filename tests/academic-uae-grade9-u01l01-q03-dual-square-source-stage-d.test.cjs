'use strict';
const test=require('node:test'), assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),base='artifacts/curriculum-delivery/UAE-MOE-MATH/G9/';
const read=n=>JSON.parse(fs.readFileSync(path.join(root,base,n),'utf8'));
test('U01L01 scanned Q03 and independent Arabic analogue both preserve the square on EACH variable',()=>{
 const source=read('u01l01-q03-dual-squared-variable-source-repair-NO_GO.json');
 const practice=read('u01l01-original-61-parallel-skill-practice.json');
 const items=practice.records.filter(x=>x.sourceItem==='U01L01-Q03');
 assert.equal(items.length,1);
 assert.equal(practice.records.length,61);
 assert.equal(items[0].independentTaskId,'G9-U01L01-T03');
 assert.equal(source.sourceMathematicalStructure,'a²−18b²');
 assert.equal(items[0].studentPrompt,'صف لفظيًا أ² − ١٢ب².');
 assert.equal(items[0].teacherExpectedEvidence,'مربع أ ناقص اثني عشر مثل مربع ب.');
 assert.equal(items[0].gradingRoute,'TEACHER_REVIEW_REQUIRED');
 const audit=read('u01l01-61-source-visual-skill-audit.json').records.find(x=>x.sourceItem==='U01L01-Q03');
 assert.match(audit.sourceCognitiveTaskSummary,/مربع متغير آخر/);
 assert.equal(audit.sourceExerciseItemFullyCertified,false);
 const html=fs.readFileSync(path.join(root,'src/Edulytics.Web/wwwroot/lesson-labs/uae-g9-general/u01-l01-original-61-practice-ar.html'),'utf8');
 assert.ok(html.includes('studentPrompt":"صف لفظيًا أ² − ١٢ب²."'));
 assert.ok(!html.includes('studentPrompt":"صف لفظيًا أ² − ١٢ب."'));
 const digest=crypto.createHash('sha256').update(html,'utf8').digest('hex');
 assert.equal(digest,source.studentActivityCurrentSha256);
 assert.equal(read('u01l01-nonnumbered-source-structure-reinspection-NO_GO.json').activitySha256,digest);
 assert.equal(read('u01l01-source-visual-structure-closure-NO_GO.json').originalStudentActivitySha256,digest);
 const checkpoint=read('lesson-1-stage-d-checkpoint.json');
 assert.equal(checkpoint.dStatus,'D_PENDING');
 assert.equal(checkpoint.stageD4Q03ExponentCorrection.newHtmlSha256,digest);
 assert.equal(source.sourceFullLessonAuditPassed,false);
 assert.equal(source.productionDeployAllowed,false);
});

'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const read=rel=>JSON.parse(fs.readFileSync(path.join(root,rel),'utf8'));
const base='artifacts/curriculum-delivery/UAE-MOE-MATH/G9/';
test('Independent Python Stage D source parity CLI exits with exactly the recorded fail-closed outcome',()=>{
 const cmd=process.platform==='win32'?'python':'python3';
 const run=spawnSync(cmd,['tools/curriculum/uae_g9_stage_d_semantic_gate.py','--json'],{cwd:root,encoding:'utf8',timeout:15000});
 if(run.error)throw run.error;
 assert.ok(run.stdout.trim().startsWith('{'),run.stderr);
 const result=JSON.parse(run.stdout);
 const raw=read(base+'semantic-audit-ledger.json').rows;
 const index=read(base+'grade9-82-target-index.json');
 const progress=read(base+'full-grade-progress.json');
 const nRaw=raw.filter(r=>r.fullLessonAuditPassed===true && Number.isInteger(r.elementCountDenominator) && r.elementCountDenominator>0 && r.objectiveCoverageVerification==='FULL_SOURCE_ATOMIC_LEDGER_VERIFIED').length;
 const nTarget=index.records.filter(r=>r.ElementCoverage==='FULL_SOURCE_ELEMENT_1_TO_1_VERIFIED').length;
 assert.equal(result.expectedRawSourceLessons,86);
 assert.equal(result.expectedCanonicalLessons,82);
 assert.equal(result.verifiedRawSourceLessons,nRaw);
 assert.equal(result.verifiedCanonicalLessons,nTarget);
 assert.equal(result.sourceIndexComplete,index.SOURCE_INDEX_COMPLETE===true);
 const sourceComplete=nRaw===86 && nTarget===82 && index.SOURCE_INDEX_COMPLETE===true && progress.targetIndexComplete===true && progress.uniqueLessonsVerified===82;
 assert.equal(result.releaseDecision,sourceComplete?'PASS':'NO_GO');
 assert.equal(run.status,sourceComplete?0:1);
 if(!sourceComplete)assert.ok(result.failures.length>0);
});
test('Python parity gate cannot overwrite source evidence or mark release successful by invocation',()=>{
 const src=fs.readFileSync(path.join(root,'tools/curriculum/uae_g9_stage_d_semantic_gate.py'),'utf8');
 assert.ok(src.includes('fullLessonAuditPassed'));
 assert.ok(src.includes('elementCountDenominator'));
 assert.ok(src.includes('FULL_SOURCE_ATOMIC_LEDGER_VERIFIED'));
 assert.ok(src.includes('FULL_SOURCE_ELEMENT_1_TO_1_VERIFIED'));
 assert.ok(src.includes('SOURCE_INDEX_COMPLETE'));
 assert.ok(src.includes('return 0 if result["releaseDecision"] == "PASS" else 1'));
 assert.ok(!src.includes('write_text('));
 assert.ok(!src.includes('.unlink('));
});

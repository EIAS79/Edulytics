  [Fact] public void SourceFrozenInventoryContains128UniqueCodes()
  {
      Assert.Equal(128,Codes.Length);
      Assert.Equal(Codes.Length,Codes.Distinct(StringComparer.Ordinal).Count());
      Assert.All(Codes,c=>Assert.StartsWith("PED:UAE-MOE-MATH:L6:GENERAL:",c));
  }
  [Theory] [MemberData(nameof(Cases))]
  public void ArabicRichLessonRendersWithoutGenericFallback(string code)
  {
      var lesson=RichLessonContentV2Registry.Find(code,"ar");
      Assert.NotNull(lesson);
      Assert.Matches("[\u0600-\u06FF]",lesson!.Title);
      Assert.NotEmpty(lesson.ExplanationParagraphs);
      Assert.NotEmpty(lesson.WorkedExamples);
      foreach(var item in lesson.WorkedExamples)
          Assert.True(item.Steps.Count>=3,code+": "+item.Title);
      Assert.NotEmpty(lesson.Visuals);
  }
  [Theory] [MemberData(nameof(Cases))]
  public void DigitalQuestionFamiliesResolveToExistingEngine(string code)
  {
      Assert.True(LessonPracticeCapabilityResolver.TryResolve(code,out var contract),
          "Missing scoped contract: "+code);
      Assert.NotNull(contract);
      Assert.NotEmpty(contract!.AllowedQuestionFamilies);
      foreach(var family in contract.AllowedQuestionFamilies)
          Assert.True(ExactSkillContractQuestionEngine.SupportsFamily(family),
              "Unregistered exact grader: "+code+" family="+family);
  }

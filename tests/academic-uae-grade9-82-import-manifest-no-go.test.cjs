'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const read=rel=>JSON.parse(fs.readFileSync(path.join(root,rel),'utf8'));
const base='artifacts/curriculum-delivery/UAE-MOE-MATH/G9/';
test('Prepared UAE Grade9 General 82-lesson import manifest reuses all existing Arabic RichV2 identities and SHA digests',()=>{
 const manifest=read(base+'grade9-82-production-import-candidate-NO_GO.json');
 const index=read(base+'grade9-82-target-index.json');
 assert.equal(manifest.kind,'PRE_RELEASE_CANDIDATE_ONLY_NOT_A_SEED');
 assert.equal(manifest.targetFramework,'UAE-MOE-MATH');
 assert.equal(manifest.targetGrade,9);
 assert.equal(manifest.targetPathway,'General');
 assert.equal(manifest.academicLanguage,'ar');
 assert.equal(manifest.expectedRawSourceLessonEntries,86);
 assert.equal(manifest.expectedUnits,13);
 assert.equal(manifest.expectedCanonicalLessons,82);
 assert.equal(manifest.items.length,82);
 assert.equal(index.records.length,82);
 const codes=new Set();const lessonsByUnit=new Map();const variants=[];
 for(let i=0;i<82;i++){
  const entry=manifest.items[i],source=index.records[i];
  const pathname=path.join(root,entry.richV2RelativePath);
  const doc=JSON.parse(fs.readFileSync(pathname,'utf8'));
  assert.equal(entry.ordinal,i+1);
  assert.equal(entry.ordinal,source.ordinal);
  assert.equal(entry.unitOrdinal,source.UnitOrdinal);
  assert.equal(entry.lessonOrdinal,source.LessonOrdinal);
  assert.equal(doc.Lessons.length,1);
  assert.equal(entry.lessonCode,doc.Lessons[0].LessonCode);
  assert.equal(entry.runtimeDisplayArabicTitle,doc.Lessons[0].Title);
  assert.equal(entry.canonicalIndexTitle,source.LessonArabicTitle);
  assert.deepEqual(entry.sourceReferences,source.SourceRefs);
  assert.equal(doc.Lessons[0].CultureCode,'ar');
  assert.equal(entry.sourceIndexParityStatus,source.ElementCoverage);
  assert.equal(entry.importStatus,'BLOCKED_SOURCE_PARITY');
  assert.equal(entry.richV2Sha256,crypto.createHash('sha256').update(fs.readFileSync(pathname)).digest('hex'));
  assert.ok(entry.lessonCode.startsWith('PED:UAE-MOE-MATH:L9:GENERAL:'));
  assert.ok(!codes.has(entry.lessonCode));codes.add(entry.lessonCode);
  lessonsByUnit.set(entry.unitOrdinal,(lessonsByUnit.get(entry.unitOrdinal)||0)+1);
  if(!entry.canonicalAndRuntimeTitlesExactMatch)variants.push(entry.ordinal);
 }
 assert.deepEqual(index.unitLessonCounts.map(x=>x.lessons),[...lessonsByUnit.values()]);
 assert.deepEqual(manifest.unresolvedIndexTitleVariants,variants);
 assert.equal(manifest.titlesExactlyMatchingCanonicalIndex,82-variants.length);
});
test('Candidate Grade9 import is permanently inert while academic source and CI gates are unverified and preserves official Advanced standards',()=>{
 const manifest=read(base+'grade9-82-production-import-candidate-NO_GO.json');
 const framework=read('src/Edulytics.Core/Curriculum/Packs/uae-moe-math.curriculum-pack.json');
 const preexisting=framework.Nodes.filter(x=>x.LogicalLevelFrom===9 && ['General','Advanced'].includes(x.Pathway));
 const remainingAdvancedStandards=preexisting.filter(x=>['Standard','Domain'].includes(x.Kind)).length;
 const oldLessons=preexisting.filter(x=>['Lesson','Unit','Grade'].includes(x.Kind)).length;
 assert.equal(oldLessons,0);
 assert.equal(manifest.priorGrade9LessonOrUnitNodesInEmbeddedPack,0);
 assert.equal(manifest.preexistingGrade9AdvancedOfficialStandardAndDomainNodesPreserved,remainingAdvancedStandards);
 assert.equal(remainingAdvancedStandards,11);
 assert.equal(manifest.allowProductionWrites,false);
 assert.equal(manifest.allowAutomaticReseeding,false);
 assert.equal(manifest.databaseWriteConnectionRequested,false);
 assert.equal(manifest.productionImportExecuted,false);
 assert.equal(manifest.candidateGithubCiPassed,false);
 assert.equal(manifest.candidateStageDAcademicSourceParityVerified,false);
 assert.equal(manifest.mergeAuthorizedByReleaseGates,false);
});
